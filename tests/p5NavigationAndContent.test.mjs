import assert from 'node:assert/strict';
import {test} from 'node:test';
import {readFileSync} from 'node:fs';
import {LEARNING_COURSES,mountLearning} from '../ui/learningExperience.js';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
test('P5 source gates: learning, nav and scientific provenance preserved',()=>{
 const app=read('app.js'),css=read('styles.css'),learnCSS=read('ui/learningExperience.css'),unified=read('ui/unifiedLearningShell.css'),explore=read('ui/explorationExperience.js');
 const learning={innerHTML:''};mountLearning(learning,new URLSearchParams());
 assert.equal((learning.innerHTML.match(/class="lr-course"/g)||[]).length,3);
 assert.equal(LEARNING_COURSES.filter(c=>c.ready).length,3);
 assert.equal(LEARNING_COURSES.length,8,'eight-slot curricular design kept internally');
 assert.doesNotMatch(learning.innerHTML,/RUNLOAD LEARNING|内部審査候補|原著・教材確認中|RunLoad独自/);
 assert.match(learning.innerHTML,/学習でできること/);
 for(const id of ['pace-basics','running-motion-basics','effort-fatigue-recovery','record-origin-missing'])assert.ok(learning.innerHTML.includes('lesson='+id));
 assert.match(app,/const mobileNav=\[\["home".*\["record-start".*\["history".*\["exploration-tree".*\["learning"/);
 assert.match(app,/const desktopNav=\[\["home".*\["record".*\["result".*\["history".*\["exploration-tree".*\["learning".*\["settings"/);
 assert.doesNotMatch(app,/class="rl-tools-menu"/,"obsolete topbar menu must be removed");
 assert.match(app,/\["settings","⚙","設定"\]/,"Settings restored in bottom nav");
 assert.match(app,/const mobileNav=\[[^;]*\["settings"/);
 assert.match(unified,/grid-template-columns:repeat\(6,minmax\(0,1fr\)\)/);
 assert.match(unified,/\.app-shell \.topbar\{display:none!important\}/);
 assert.doesNotMatch(learnCSS,/grid-template-columns:repeat\(6,minmax\(0,1fr\)\)/);
 assert.match(explore,/data-ex-action="field-help"/);
 assert.match(explore,/class="ex-related-learning"/);
 assert.match(explore,/学習から探究に移りました。走行記録は未選択です。/);
 assert.match(app,/fromLearning&&saved\.ok===true\?\{ok:true,records:\[\]\}/);
 assert.match(read('ui/resultExperience.js'),/data-compare-date/,'new main date wrap correction retained');
 assert.match(read('ui/resultInlineStyles.js'),/\.rv4-region-compare-date/);
 assert.match(read('sw.js'),/resultExperience\.js\?v=20261110-public-copy-v1/);
 assert.match(read('sw.js'),/ui\/learningExperience\.js/);
});
