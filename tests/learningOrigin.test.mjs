import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {test} from 'node:test';
import {ORIGIN_LESSON,ORIGIN_QUIZ,evaluateOriginQuiz,assessOriginExample,originMarkup}
 from '../ui/learningOriginLesson.js';
test('L2 candidate is bounded to K04/K05 general knowledge',()=>{
 assert.equal(ORIGIN_LESSON.id,'record-origin-missing');
 assert.equal(ORIGIN_LESSON.courseId,'data');
 assert.equal(ORIGIN_QUIZ.length,4);
 assert.ok(ORIGIN_QUIZ.every(q=>q.choices.length===3&&q.reasons.length===3&&q.relearn.startsWith('lo-')));
 assert.deepEqual(evaluateOriginQuiz({o1:'1',o2:'1',o3:'2',o4:'1'}).map(x=>x.correct),[true,true,true,true]);
 assert.deepEqual(evaluateOriginQuiz({o1:'0',o2:'0',o3:'0',o4:'0'}).map(x=>x.correct),[false,false,false,false]);
 assert.deepEqual(evaluateOriginQuiz({}).map(x=>x.correct),[false,false,false,false]);
 assert.match(evaluateOriginQuiz({})[0].reason,/未回答/);
 assert.equal(assessOriginExample('derived').correct,true);
 assert.equal(assessOriginExample('input').correct,false);
 assert.equal(assessOriginExample('gps').correct,false);
 assert.equal(assessOriginExample('reference').correct,false);
 assert.equal(assessOriginExample('').correct,false);
 const html=originMarkup();
 assert.match(html,/ROF-J：0（有効な回答）/);
 assert.match(html,/ROF-J：未回答（値なし）/);
 assert.match(html,/読取失敗/);
 assert.match(html,/後日申告/);
 assert.match(html,/適用範囲外の不算出/);
 assert.match(html,/仮想例/);
 assert.match(html,/記録を選ぶ/);
 assert.equal((html.match(/class="lr-question"/g)||[]).length,4);
 assert.doesNotMatch(html,/あなたの理解度が向上した|安全と保証|医学的に正常/);
 const source=readFileSync(new URL('../ui/learningOriginLesson.js',import.meta.url),'utf8');
 assert.doesNotMatch(source,/localStorage\.|sessionStorage\.|indexedDB\.|readManualRuns\(|saveManualRun\(|inspectPostHoc\(/);
 const app=readFileSync(new URL('../app.js',import.meta.url),'utf8');
 const shell=readFileSync(new URL('../sw.js',import.meta.url),'utf8');
 const index=readFileSync(new URL('../index.html',import.meta.url),'utf8');
 assert.match(app,/learningExperience\.js\?v=20261111-explore-controls-v1/);
 const appAsset=index.match(/src="(\.\/app\.js\?v=[a-z0-9-]+)"/)?.[1];
 assert.ok(appAsset,'versioned app entry must exist');
 const assets=JSON.parse(shell.match(/const ASSETS=(\[[^\n]*\]);/)[1]);
 assert.ok(assets.includes(appAsset),'offline shell must cache the current app entry');
 assert.match(shell,/"\.\/ui\/learningOriginLesson\.js\?v=20261111-explore-controls-v1"/);
});
