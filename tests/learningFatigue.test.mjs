import assert from 'node:assert/strict';
import {test} from 'node:test';
import {readFileSync} from 'node:fs';
import {FATIGUE_LESSON,FATIGUE_QUESTIONS,FATIGUE_SCENARIOS,evaluateFatigueQuestions,assessFatigueScenario,fatigueMarkup}
 from '../ui/learningFatigueLesson.js';
import {LEARNING_COURSES} from '../ui/learningExperience.js';
test('L5 running exertion, perceived fatigue and recovery is bounded general knowledge',()=>{
 assert.equal(FATIGUE_LESSON.id,'effort-fatigue-recovery');
 assert.equal(FATIGUE_LESSON.courseId,'fatigue');
 assert.equal(LEARNING_COURSES.length,8);
 assert.equal(LEARNING_COURSES.find(c=>c.id==='fatigue').ready,true);
 assert.equal(LEARNING_COURSES.filter(c=>c.ready).length,3);
 assert.equal(FATIGUE_QUESTIONS.length,4);
 assert.ok(FATIGUE_QUESTIONS.every(q=>q.choices.length===3&&q.reasons.length===3&&q.relearn.startsWith('lf-')));
 assert.deepEqual(evaluateFatigueQuestions({f1:'1',f2:'0',f3:'1',f4:'0'}).map(x=>x.correct),[true,true,true,true]);
 assert.deepEqual(evaluateFatigueQuestions({f1:'2',f2:'1',f3:'0',f4:'1'}).map(x=>x.correct),[false,false,false,false]);
 assert.deepEqual(evaluateFatigueQuestions({}).map(x=>x.correct),[false,false,false,false]);
 assert.match(evaluateFatigueQuestions({})[0].reason,/未回答/);
 assert.match(evaluateFatigueQuestions({f1:'7'})[0].reason,/未回答/);
 assert.equal(assessFatigueScenario('different').correct,true);
 assert.equal(assessFatigueScenario('equal').correct,false);
 assert.equal(assessFatigueScenario('prescribe').correct,false);
 assert.equal(assessFatigueScenario('').valid,false);
 assert.equal(assessFatigueScenario('unknown').valid,false);
 assert.equal(FATIGUE_SCENARIOS.length,3);
 const html=fatigueMarkup();
 for(const term of ['走行中','走行後','生活・睡眠','3 km','18分','RPE','ROF-J','Borg','Micklewright','Suzuki','Walsh','85名','35名','自転車運動','30分','ナラティブレビュー'])
  assert.ok(html.includes(term),'missing learning concept '+term);
 assert.match(html,/本人がこの2つの感覚を常に明瞭に区別できるとは限りません/);
 assert.match(html,/一律の処方ではありません/);
 assert.match(html,/本アプリの利用者を対象とした介入試験ではありません/);
 assert.match(html,/class="lr-lesson-title"/);
 assert.doesNotMatch(html,/アプリの操作手順ではありません/);
 assert.match(html,/#\/exploration-tree\?category=04&amp;topic=/);
 assert.equal((html.match(/class="lr-question"/g)||[]).length,4);
 assert.match(html,/data-lf-practice/);
 assert.match(html,/lr-fatigue-cycle/);
 assert.doesNotMatch(html,/本人の休養日数を求めます|正しい運動強度に修正|危険度を算出|ROF-JからRPEへ換算/);
 const source=readFileSync(new URL('../ui/learningFatigueLesson.js',import.meta.url),'utf8');
 assert.doesNotMatch(source,/localStorage\.|sessionStorage\.|indexedDB\.|readManualRuns\(|saveManualRun\(|readGpsRuns\(|fetch\(/);
 const sw=readFileSync(new URL('../sw.js',import.meta.url),'utf8');
 const index=readFileSync(new URL('../index.html',import.meta.url),'utf8');
 const app=readFileSync(new URL('../app.js',import.meta.url),'utf8');
 assert.match(sw,/"\.\/ui\/learningFatigueLesson\.js\?v=20261111-explore-controls-v1"/);
 assert.match(sw,/runload-ui-next-shell-20261112-cleanup8-final-v1/);
 assert.match(index,/learningExperience\.css\?v=20261111-learning-density-v1/);
 const current=index.match(/app\.js\?v=([\w-]+)/)?.[1];
 assert.ok(current,'app entry must be versioned');
 assert.ok(sw.includes('app.js?v='+current),'app entry must be available offline');
 assert.match(app,/learningExperience\.js\?v=20261111-explore-controls-v1/);
});
